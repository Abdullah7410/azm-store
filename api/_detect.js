/** السيارات المذكورة في اسم الصنف، من قائمة السيارات في قاعدة البيانات */
export function carsOf(name, carNames) {
  const n = norm(name).toUpperCase();
  const out = [];
  for (const c of carNames) {
    const keys = [c, ...(ALIASES[c] || [])].map((k) => norm(k).toUpperCase());
    if (keys.some((k) => k && n.includes(k))) out.push(c);
  }
  return out;
}

/** السنوات من اسم الصنف: 2012-2016 أو 2012/2016 أو سنة واحدة */
export function yearsOf(name) {
  const ys = (String(name).match(/(?:19|20)\d{2}/g) || []).map(Number).filter((y) => y >= 1990 && y <= new Date().getFullYear() + 1);
  if (!ys.length) return [null, null];
  return [Math.min(...ys), Math.max(...ys)];
}
