export const CAT_NAMES = Object.fromEntries([...CATS.map((c) => [c[0], c[1]]), ["etc", "قطع أخرى"]]);

const norm = (s) => String(s || "").replace(/[أإآ]/g, "ا").replace(/ة\b/g, "ه").replace(/ى/g, "ي");

/** النوع من آخر حرف في رقم القطعة: رقم = وكالة، M = موبس، K = كوري، حرف آخر = تجاري */
export function typeOf(partNo) {
  const last = String(partNo).trim().slice(-1).toUpperCase();
  if (/\d/.test(last)) return "a";
  if (last === "M") return "m";
  if (last === "K") return "k";
  return "c";
}

export function categoryOf(name) {
  const ws = String(name).replace(/[()]/g, " ").split(/\s+/);
  const hit = (w) => CATS.find((c) => c[2].includes(w));
  for (const w of ws.slice(0, 2)) { const c = hit(w); if (c) return c[0]; }
  for (const w of ws) { const c = hit(w); if (c) return c[0]; }
  return "etc";
}

/** رمز الجيل: أول خانتين بعد الشرطة في رقم القطعة (58101-F2A00 → F2) */
export function genCodeOf(partNo) {
  const m = String(partNo).toUpperCase().match(/^[0-9A-Z]{5}-?([0-9A-Z]{2})/);
  return m ? m[1] : null;
}

